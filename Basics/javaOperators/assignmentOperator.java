
public class assignmentOperator {
   public static void main(String[] args) {

        int a = 10; // simple assignment operator
        System.out.println("value of a : " + a); // 10

        a += 5; // a = a + 5; 15
        System.out.println("value of a after addition assignment : " + a);// 15

        a -= 5; // a = a - 5; 10 
        System.out.println(" value of a after substraction assignment : "  + a); // 10 
        
        a *= 5; // a = a * 5; 50
        System.out.println("value of a after multiplication assignment : " + a);// 50

        a /= 10; // a = a / 10; 5
        System.out.println("value of a after division assignment : " + a);// 5

        a %= 3; // a = a % 3; 2
        System.out.println("value of a after modulus assignment : " + a); //2

 }


}
